import { mkdir, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { createHash } from 'node:crypto'

const FONT_CSS_URL =
  'https://fonts.googleapis.com/css2?family=Inter:wght@300..600&family=Playfair+Display:ital,wght@0,400..700;1,400..600&family=Hind+Siliguri:wght@400;500;600;700&display=swap'

const UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/125.0 Safari/537.36'

const root = path.resolve(import.meta.dirname, '..')
const fontDir = path.join(root, 'public', 'fonts')
const cssOut = path.join(root, 'src', 'styles', 'fonts.css')

await mkdir(fontDir, { recursive: true })
await mkdir(path.dirname(cssOut), { recursive: true })

const css = await fetch(FONT_CSS_URL, { headers: { 'User-Agent': UA } }).then((r) => {
  if (!r.ok) throw new Error(`Font CSS request failed: ${r.status}`)
  return r.text()
})

// Split into @font-face blocks while keeping each block's preceding subset comment.
const blocks = css.split('@font-face').slice(1)
const out = []
const downloaded = new Set()

for (const raw of blocks) {
  const block = `@font-face${raw}`
  const family = block.match(/font-family:\s*'([^']+)'/)?.[1]
  const style = block.match(/font-style:\s*(\w+)/)?.[1] ?? 'normal'
  const weight = block.match(/font-weight:\s*([\d\s]+);/)?.[1]?.trim() ?? '400'
  const url = block.match(/url\((https:\/\/[^)]+)\)/)?.[1]
  const range = block.match(/unicode-range:\s*([^;]+);/)?.[1]
  if (!url || !family) continue

  const rangeText = range ?? ''
  const subset = rangeText.includes('U+0980') ? 'bengali' : rangeText.includes('U+0100') ? 'latin-ext' : 'latin'
  const slug = family.toLowerCase().replace(/[^a-z0-9]+/g, '-')
  const hash = createHash('sha1').update(url).digest('hex').slice(0, 8)
  const dedupeKey = hash

  // Variable fonts reuse one file across several unicode ranges — download each unique URL once.
  const fileName = `${slug}-${weight.replace(/\s+/g, '-')}-${style}-${subset}-${dedupeKey}.woff2`
  const filePath = path.join(fontDir, fileName)
  if (!downloaded.has(dedupeKey)) {
    const res = await fetch(url, { headers: { 'User-Agent': UA } })
    if (!res.ok) throw new Error(`Font download failed (${family} ${weight}): ${res.status}`)
    await writeFile(filePath, Buffer.from(await res.arrayBuffer()))
    downloaded.add(dedupeKey)
  }

  out.push(
    `@font-face {
  font-family: '${family}';
  font-style: ${style};
  font-weight: ${weight};
  font-display: swap;
  src: url('/fonts/${fileName}') format('woff2');${range ? `\n  unicode-range: ${range};` : ''}
}`,
  )
  console.log(`font  ${fileName}`)
}

const header = '/* Self-hosted webfonts — Playfair Display, Inter, Hind Siliguri. Generated by scripts/fetch-fonts.mjs */\n\n'
await writeFile(cssOut, header + out.join('\n\n') + '\n')
console.log(`\nWrote ${out.length} @font-face rules to src/styles/fonts.css`)
